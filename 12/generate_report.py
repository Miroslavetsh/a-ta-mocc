# справжню невизначеність. Коректний спосіб — кілька незалежних реплікацій (різні seed) і ДІ за їх середніми.
def replicated_wq(lam, mu, c, n_reps=30, n_jobs=30_000, seed0=9000):
    means = np.array([simulate(lam, mu, c, n_jobs=n_jobs, seed=seed0 + c * 1000 + i)["Wq"] for i in range(n_reps)])
    m = float(means.mean())
    ci = float(1.96 * means.std(ddof=1) / math.sqrt(n_reps))
    return m, ci


