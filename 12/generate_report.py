# ---------- Імітаційна модель (дискретно-подійна, метод Монте-Карло) ----------
def simulate(lam, mu, c, n_jobs=50_000, seed=0, warm_frac=0.1):
    rng = np.random.default_rng(seed)
    arr = np.cumsum(rng.exponential(1 / lam, n_jobs))
    srv = rng.exponential(1 / mu, n_jobs)

    free = [0.0] * c
    heapq.heapify(free)
    wait = np.empty(n_jobs)
    for i in range(n_jobs):
        t = heapq.heappop(free)
        start = max(arr[i], t)
        wait[i] = start - arr[i]
        heapq.heappush(free, start + srv[i])

    warm = int(n_jobs * warm_frac)
    w = wait[warm:]
    ci = 1.96 * w.std(ddof=1) / math.sqrt(len(w))
    return dict(Wq=float(w.mean()), Lq=float(w.mean() * lam), p_wait=float((w > 1e-12).mean()),
                ci=float(ci), n_used=len(w))


