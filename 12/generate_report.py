def best_c(lam, mu, cs, cw, span=25):
    cmin = math.ceil(lam / mu)
    best_ = None
    for c in range(cmin, cmin + span):
        a = mmc(lam, mu, c)
        if a is None:
            continue
        cost = cs * c + cw * a["Lq"]
        if best_ is None or cost < best_[1]:
            best_ = (c, cost, a)
    return best_


