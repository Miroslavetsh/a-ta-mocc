# ---------- Додатково: інші розподіли часу обслуговування (M/G/c) ----------
def simulate_general(lam, mu, c, dist, n_jobs=50_000, seed=0, warm_frac=0.1):
    rng = np.random.default_rng(seed)
    arr = np.cumsum(rng.exponential(1 / lam, n_jobs))
    if dist == "exp":
        srv = rng.exponential(1 / mu, n_jobs)
    elif dist == "uniform":
        srv = rng.uniform(0, 2 / mu, n_jobs)
    else:
        srv = np.full(n_jobs, 1 / mu)

    free = [0.0] * c
    heapq.heapify(free)
    wait = np.empty(n_jobs)
    for i in range(n_jobs):
        t = heapq.heappop(free)
        start = max(arr[i], t)
        wait[i] = start - arr[i]
        heapq.heappush(free, start + srv[i])
    w = wait[int(n_jobs * warm_frac):]
    return dict(Wq=float(w.mean()), Lq=float(w.mean() * lam), ci=float(1.96 * w.std(ddof=1) / math.sqrt(len(w))))


