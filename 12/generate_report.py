# ---------- Аналітична модель M/M/c (формули Ерланга) ----------
def mmc(lam, mu, c):
    rho = lam / (c * mu)
    if rho >= 1:
        return None
    a = lam / mu
    s = sum(a ** k / math.factorial(k) for k in range(c))
    p0 = 1 / (s + a ** c / (math.factorial(c) * (1 - rho)))
    Lq = p0 * a ** c * rho / (math.factorial(c) * (1 - rho) ** 2)
    Wq = Lq / lam
    return dict(rho=rho, p0=p0, Lq=Lq, Wq=Wq, L=Lq + a, W=Wq + 1 / mu)


